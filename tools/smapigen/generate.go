package main

import (
	"cmp"
	"fmt"
	"maps"
	"runtime/debug"
	"slices"
	"strings"

	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
)

func generate(raw []byte, pkg string) ([]byte, error) {
	pre, err := assignOperationIDs(raw)
	if err != nil {
		return nil, err
	}
	doc, err := toOpenAPI3(pre)
	if err != nil {
		return nil, err
	}
	fixRequestBodies(doc)
	if err := checkOperations(doc, operations); err != nil {
		return nil, err
	}

	cfg := codegen.Configuration{
		PackageName: pkg,
		Generate: codegen.GenerateOptions{
			Models: true,
			Client: true,
		},
		Compatibility: codegen.CompatibilityOptions{
			// SMAPI reuses enum values (e.g. "SUCCEEDED") across many types.
			AlwaysPrefixEnumValues: true,
		},
		OutputOptions: codegen.OutputOptions{
			IncludeOperationIDs: slices.Clone(operations),
			NameNormalizer:      string(codegen.NameNormalizerFunctionToCamelCaseWithInitialisms),
			// A nil slice or map already means "absent".
			PreferSkipOptionalPointerOnContainerTypes: true,
		},
		AllowRemoteRefsFrom: []string{},
	}
	src, err := codegen.Generate(doc, cfg)
	if err != nil {
		return nil, err
	}
	return replaceHeader(src, pkg)
}

// replaceHeader swaps oapi-codegen's header, which embeds the build's VCS version of the tools module, for a deterministic one.
func replaceHeader(src, pkg string) ([]byte, error) {
	i := strings.Index(src, "\npackage "+pkg+"\n")
	if i < 0 {
		return nil, fmt.Errorf("generated code has no package clause")
	}
	version := "unknown"
	if bi, ok := debug.ReadBuildInfo(); ok {
		for _, dep := range bi.Deps {
			if dep.Path == oapiCodegenModule {
				version = dep.Version
			}
		}
	}
	// The blank line keeps the header from becoming a second package comment; doc.go holds the real one.
	header := fmt.Sprintf("// Code generated by smapigen using oapi-codegen %s. DO NOT EDIT.\n", version)
	return []byte(header + src[i:]), nil
}

func sortedKeys[K cmp.Ordered, V any](m map[K]V) []K {
	return slices.Sorted(maps.Keys(m))
}
